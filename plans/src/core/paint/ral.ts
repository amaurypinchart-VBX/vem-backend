export const RAL_CLASSIC: RalColor[] = T.map(([code, hex, fr, en, de]) => ({ code, hex, fr, en, de }));

export const RAL_BY_CODE = new Map(RAL_CLASSIC.map((c) => [c.code, c]));

/** sans accents, minuscules (« Tiefschwarz » = « tiefschwarz », « gris fenêtre » = « gris fenetre ») */
export const fold = (s: string) =>
  s
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/ß/g, 'ss')
    .toLowerCase()
    .trim();

/**
 * Recherche RAL par code (« 9005 », « RAL 9005 », « 90 ») ou par nom en français, anglais ou allemand (« noir foncé »,
 * « jet black », « Tiefschwarz ») ; les codes exacts d'abord, puis les débuts de code, puis les noms.
 */
export function searchRal(query: string, limit = 30): RalColor[] {
  const q = fold(query).replace(/^ral\s*/, '');
  if (!q) return RAL_CLASSIC.slice(0, limit);
  const words = q.split(/\s+/);
  const scored: Array<{ c: RalColor; s: number }> = [];
  for (const c of RAL_CLASSIC) {
    let s = -1;
    if (c.code === q) s = 0;
    else if (c.code.startsWith(q)) s = 1;
    else {
      const names = [c.fr, c.en, c.de].map(fold);
      if (names.some((n) => n === q)) s = 2;
      else if (names.some((n) => words.every((w) => n.includes(w)))) s = 3;
    }
    if (s >= 0) scored.push({ c, s });
  }
  return scored
    .sort((a, b) => a.s - b.s || a.c.code.localeCompare(b.c.code))
    .slice(0, limit)
    .map((x) => x.c);
}
